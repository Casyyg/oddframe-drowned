import {copyFileSync,existsSync,readFileSync,writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {resolve} from 'node:path';
const [id,source,filename]=process.argv.slice(2);
if(!['long-corridor','nameless','check-in','surface'].includes(id)||!source||!filename||!/^[-a-z0-9]+\.mp4$/.test(filename))throw new Error('Expected scene, source path, unique MP4 filename.');
const ffmpeg='/Users/casgao/Desktop/SPI/615/Ass4/work/oddframe/deps/imageio_ffmpeg/binaries/ffmpeg-macos-aarch64-v7.1';
const root=resolve('public/media/drowned');
const target=resolve(root,filename);
if(existsSync(target))throw new Error('Preserve existing revision: '+target);
const decode=spawnSync(ffmpeg,['-hide_banner','-i',resolve(source),'-f','null','-'],{encoding:'utf8'});
if(decode.status||!decode.stderr.includes('Audio:'))throw new Error('Video must fully decode and contain audio.');
const match=/Duration: (\d+):(\d+):([\d.]+)/.exec(decode.stderr);
if(!match)throw new Error('Missing duration');
copyFileSync(source,target);
const poster=filename.replace('.mp4','.jpeg');
const capture=spawnSync(ffmpeg,['-hide_banner','-i',target,'-frames:v','1','-q:v','2',resolve(root,poster)],{encoding:'utf8'});
if(capture.status)throw new Error(capture.stderr);
const path=resolve(root,'story.json');const story=JSON.parse(readFileSync(path,'utf8'));const scene=story.scenes.find(s=>s.id===id);
scene.video=filename;scene.poster=poster;scene.duration=+match[1]*3600 + +match[2]*60 + +match[3];
delete scene.captions;
scene.productionNote='New Flow-generated picture and audio. Visual continuity checked; final listening and dialogue review remains required.';
writeFileSync(path,JSON.stringify(story,null,2)+'\n');console.log({id,filename,duration:scene.duration});
